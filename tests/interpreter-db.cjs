// Real PostgreSQL tests. Run against an isolated Docker container, never production.
const {execFileSync,execFile}=require('node:child_process');
const {randomUUID}=require('node:crypto');const assert=require('node:assert/strict');
const container=process.env.INTERPRETER_TEST_CONTAINER||'metro-interpreter-db-20261117';
const command=['exec','-i','-e','PGOPTIONS=-c role=service_role',container,'psql','-U','postgres','-tA','-v','ON_ERROR_STOP=1'];
const sql=q=>execFileSync('docker',command,{input:q,encoding:'utf8'}).trim();
const run=q=>new Promise((resolve,reject)=>{const p=execFile('docker',command,{encoding:'utf8'},(e,out,err)=>e?reject(Error(err)):resolve(out.trim()));p.stdin.end(q);});
const rpc=(fn,args)=>`select public.${fn}(${args.map(x=>"'"+x.replaceAll("'","''")+"'").join(',')});`;
const create=()=>{const id=randomUUID();sql(`insert into public.interpreter_test_rooms(id,station_code,staff_token_hash,guest_invite_hash,guest_token_hash,creator_ip_hash,expires_at) values('${id}','0154','s','i','g','test',now()+interval '30 minutes');`);return id;};
(async()=>{
 const r=create(),req=randomUUID(),a=randomUUID();
 const claim=()=>rpc('interpreter_claim',[r,'staff',req,'fingerprint',a]);
 assert.equal(JSON.parse(sql(claim())).state,'claimed');
 assert.equal(JSON.parse(sql(claim())).error,'message-pending');
 assert.equal(JSON.parse(sql(rpc('interpreter_claim',[r,'staff',req,'other',a]))).error,'request-conflict');
 sql(`update public.interpreter_test_rooms set guest_lang='ja' where id='${r}';`);
 sql(rpc('interpreter_fail',[r,'staff',req,a]));const a2=randomUUID();
 assert.equal(JSON.parse(sql(rpc('interpreter_claim',[r,'staff',req,'fingerprint',a2]))).targetLang,'en');
 assert.equal(JSON.parse(sql(rpc('interpreter_finish',[r,'staff',req,a,'hello','안녕']))).error,'request-conflict');
 sql(rpc('interpreter_finish',[r,'staff',req,a2,'hello','안녕']));
 assert.equal(JSON.parse(sql(claim())).state,'completed');
 assert.equal(sql(`select count(*) from public.interpreter_test_messages where room_id='${r}';`),'1');
 const race=create();
 const attempts=await Promise.all(Array.from({length:40},(_,i)=>run(rpc('interpreter_claim',[race,i%2?'staff':'guest',randomUUID(),'x',randomUUID()]))));
 assert.equal(attempts.map(JSON.parse).filter(x=>x.state==='claimed').length,36);
 const room=create(),qs=Array.from({length:36},()=>[room,'staff',randomUUID(),'x',randomUUID()]);
 for(const q of qs)sql(rpc('interpreter_claim',q));
 await Promise.all(qs.map(q=>run(rpc('interpreter_finish',[q[0],q[1],q[2],q[4],'hi','안녕']))));
 assert.equal(sql(`select message_count from public.interpreter_test_rooms where id='${room}';`),'36');
 assert.equal(sql(`select count(*) from public.interpreter_test_messages where room_id='${room}';`),'36');
 const closing=create(),cid=randomUUID(),ca=randomUUID();sql(rpc('interpreter_claim',[closing,'guest',cid,'x',ca]));
 await Promise.all([run(rpc('interpreter_close',[closing])),run(rpc('interpreter_finish',[closing,'guest',cid,ca,'hi','안녕']))]);
 assert.equal(sql(`select count(*) from public.interpreter_test_messages where room_id='${closing}';`),'0');
 assert.equal(JSON.parse(sql(rpc('interpreter_claim',[closing,'staff',randomUUID(),'x',randomUUID()]))).error,'room-ended');
 const topic=sql(`select realtime_topic from public.interpreter_test_rooms where id='${room}';`);
 assert.equal(sql(`set role anon;select interpreter_private.can_listen('${topic}');`),'SET\nt');
 assert.equal(sql(`set role anon;select interpreter_private.can_listen('interpreter:wrong');`),'SET\nf');
 assert.equal(sql(`select has_function_privilege('anon','public.interpreter_close(uuid)','execute');`),'f');
 assert.equal(sql(`select has_table_privilege('anon','public.interpreter_test_messages','select');`),'f');
 assert.equal(sql(`select count(*) from realtime.messages where payload<>'{}'::jsonb;`),'0');
 sql(`delete from public.interpreter_test_rooms where creator_ip_hash='test';`);
 console.log('PASS: idempotency, conflict, fixed languages, stale attempt, 40-way claim limit, 36-way count, close race, anonymous denial, notification payload');
})().catch(e=>{console.error(e);process.exitCode=1;});
